// #1044: an install from before has a collab patch without the page rows; the refresh swaps it
// for the embedded one (old kept beside it), and the page packages are in place before the staged
// dependency install that links them.
func TestRefreshDSH_UpgradesPrePagesPatch(t *testing.T) {
	dir := installedDSH(t)
	data := t.TempDir()
	t.Setenv("CONEST_COLLAB_DATA", data)
	oldPatch := "- insert:\n    - id: conest-collab\n      name: conest-collab\n- insert:\n    - id: conest-channels-ui\n      name: '@deepseek-ai/dsh-experimental-client-ui-discord'\n"
	if err := os.WriteFile(filepath.Join(dir, "collab", "cordis.patch.yml"), []byte(oldPatch), 0o644); err != nil {
		t.Fatal(err)
	}
	// The old channels UI had the desk and the panel, not other computers yet.
	oldClient := filepath.Join(dir, "packages", "client-ui-discord", "lib", "client.js")
	_ = os.MkdirAll(filepath.Dir(oldClient), 0o755)
	if err := os.WriteFile(oldClient, []byte(`const DESK_ID = "collab-desk"; const B = "bothouse-panel";`), 0o644); err != nil {
		t.Fatal(err)
	}
	withInstall(t, func(stage string) error {
		for _, name := range []string{"bothouse-dsh-desk", "bothouse-dsh-panel", "bothouse-dsh-devices"} {
			// pnpm resolves link:../packages/<name> from the staging dir.
			if _, err := os.Stat(filepath.Join(stage, "..", "packages", name, "package.json")); err != nil {
				t.Errorf("%s not in place before the dependency install: %v", name, err)
			}
		}
		return nil
	})
	if ok, err := RefreshEmbeddedDSH(dir, "v0.1.5"); err != nil || !ok {
		t.Fatalf("refresh = %v %v", ok, err)
	}
	sub, _ := fs.Sub(embeddedDSH, "dsh_bundle")
	want, _ := fs.ReadFile(sub, "collab/cordis.patch.yml")
	got, _ := os.ReadFile(filepath.Join(dir, "collab", "cordis.patch.yml"))
	if !bytes.Equal(got, want) {
		t.Errorf("old collab patch kept:\n%s", got)
	}
	if bak, _ := os.ReadFile(filepath.Join(dir, "collab", "cordis.patch.yml.bak-pre1044")); string(bak) != oldPatch {
		t.Errorf("old patch not kept beside it: %q", bak)
	}
	if note, _ := os.ReadFile(filepath.Join(data, pagesBeforeFile)); string(note) != `{"rows":["bothouse-desk","bothouse-panel"]}` {
		t.Errorf("pages-before note = %q", note)
	}
}

// A patch that already has the page rows is the user's (or ours): never replaced.
func TestRefreshDSH_KeepsCurrentPatch(t *testing.T) {
	dir := installedDSH(t)
	data := t.TempDir()
	t.Setenv("CONEST_COLLAB_DATA", data)
	mine := "# edited\n- insert:\n    - id: bothouse-desk\n      name: bothouse-dsh-desk\n"
	if err := os.WriteFile(filepath.Join(dir, "collab", "cordis.patch.yml"), []byte(mine), 0o644); err != nil {
		t.Fatal(err)
	}
	withInstall(t, func(string) error { return nil })
	if _, err := RefreshEmbeddedDSH(dir, "v0.1.5"); err != nil {
		t.Fatal(err)
	}
	if got, _ := os.ReadFile(filepath.Join(dir, "collab", "cordis.patch.yml")); string(got) != mine {
		t.Errorf("current patch replaced: %q", got)
	}
	if _, err := os.Stat(filepath.Join(dir, "collab", "cordis.patch.yml.bak-pre1044")); !os.IsNotExist(err) {
		t.Error("backup written for a current patch")
	}
	if _, err := os.Stat(filepath.Join(data, pagesBeforeFile)); !os.IsNotExist(err) {
		t.Error("pages-before note written for a current patch")
	}
}

// The embedded collab patch: channels on, the three pages off, each page package embedded.
func TestEmbeddedPagesRows(t *testing.T) {
	sub, _ := fs.Sub(embeddedDSH, "dsh_bundle")
	patch, _ := fs.ReadFile(sub, "collab/cordis.patch.yml")
	for _, row := range []string{"bothouse-desk", "bothouse-panel", "bothouse-devices"} {
		i := strings.Index(string(patch), "id: "+row+"\n")
		if i < 0 {
			t.Fatalf("collab patch has no %s row", row)
		}
		if rest := string(patch[i:]); !strings.Contains(strings.SplitN(rest, "- id:", 2)[0], "disabled: true") {
			t.Errorf("%s must start off", row)
		}
		name := strings.Replace(row, "bothouse-", "bothouse-dsh-", 1)
		if _, err := fs.Stat(sub, "packages/"+name+"/client.js"); err != nil {
			t.Errorf("%s not embedded: %v", name, err)
		}
	}
	if strings.Contains(strings.SplitN(string(patch[strings.Index(string(patch), "id: conest-channels-ui"):]), "- id:", 2)[0], "disabled") {
		t.Error("channels must stay on by default")
	}
}

// The embedded page packages are the committed ones in dsh/packages (generated by bothouse-embeds).
func TestDSHBundlePagePackagesMatchSource(t *testing.T) {
	for _, name := range []string{"bothouse-dsh-desk", "bothouse-dsh-panel", "bothouse-dsh-devices"} {
		bundle := filepath.Join("dsh_bundle", "packages", name)
		source := filepath.Join("..", "..", "dsh", "packages", name)
		if _, err := os.Stat(source); err != nil {
			t.Skipf("source tree not present: %v", err)
		}
		err := filepath.WalkDir(source, func(p string, d fs.DirEntry, err error) error {
			if err != nil || d.IsDir() {
				return err
			}
			rel, _ := filepath.Rel(source, p)
			want, _ := os.ReadFile(p)
			got, err := os.ReadFile(filepath.Join(bundle, rel))
			if err != nil || !bytes.Equal(got, want) {
				t.Errorf("%s/%s: dsh_bundle copy differs from dsh/packages; copy dsh/packages/%s into bridge/core/dsh_bundle/packages", name, rel, name)
			}
			return nil
		})
		if err != nil {
			t.Fatal(err)
		}
	}
}

// A failed dependency install leaves the old patch: the old plugin must not see the new rows.
func TestRefreshDSH_FailedInstallKeepsOldPatch(t *testing.T) {
	dir := installedDSH(t)
	t.Setenv("CONEST_COLLAB_DATA", t.TempDir())
	oldPatch := "- insert:\n    - id: conest-collab\n      name: conest-collab\n"
	if err := os.WriteFile(filepath.Join(dir, "collab", "cordis.patch.yml"), []byte(oldPatch), 0o644); err != nil {
		t.Fatal(err)
	}
	withInstall(t, func(string) error { return os.ErrPermission })
	if ok, err := RefreshEmbeddedDSH(dir, "v0.1.5"); err == nil || ok {
		t.Fatalf("refresh = %v %v, want the install error", ok, err)
	}
	if got, _ := os.ReadFile(filepath.Join(dir, "collab", "cordis.patch.yml")); string(got) != oldPatch {
		t.Errorf("patch changed after a failed install: %q", got)
	}
	if _, err := os.Stat(filepath.Join(dir, "packages", "client-ui-discord")); !os.IsNotExist(err) {
		t.Error("channels UI refreshed although the install failed")
	}
}

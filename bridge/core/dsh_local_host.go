package core

import (
	"encoding/json"
	"fmt"
	"net"
	"net/url"
	"os"
	"path/filepath"
	"strconv"
	"strings"
)

// LocalDSHHost is the current owner of the local Channels data directory.
type LocalDSHHost struct {
	target     string
	dataDir    string
	ownerToken string
}

// FindLocalDSHHost reads the private owner record published by the Channels plugin.
// DSH Desktop may change ports when it starts, so callers resolve the host when needed.
func FindLocalDSHHost() (LocalDSHHost, bool) {
	dir := collabDataDir()
	b, err := os.ReadFile(filepath.Join(dir, "collab.owner.json"))
	if err != nil {
		return LocalDSHHost{}, false
	}
	var owner struct {
		PID   int `json:"pid"`
		Local struct {
			Origin string `json:"origin"`
			Token  string `json:"token"`
		} `json:"local"`
	}
	if json.Unmarshal(b, &owner) != nil || owner.PID <= 0 || !processAlive(owner.PID) {
		return LocalDSHHost{}, false
	}
	u, err := url.Parse(owner.Local.Origin)
	if err != nil || u.Scheme != "http" || u.User != nil || u.Opaque != "" ||
		(u.Path != "" && u.Path != "/") || u.RawQuery != "" || u.ForceQuery || u.Fragment != "" {
		return LocalDSHHost{}, false
	}
	ip := net.ParseIP(u.Hostname())
	port, err := strconv.Atoi(u.Port())
	if ip == nil || !ip.IsLoopback() || err != nil || port < 1 || port > 65535 ||
		owner.Local.Token == "" || strings.ContainsAny(owner.Local.Token, "\r\n") {
		return LocalDSHHost{}, false
	}
	return LocalDSHHost{target: u.Host, dataDir: dir, ownerToken: owner.Local.Token}, true
}

// BotGateway returns the loopback origin and the default bot credential
// generated by the Channels plugin (dsh/collab/bridge.mjs).
func (h LocalDSHHost) BotGateway() (origin, token string, err error) {
	b, err := os.ReadFile(filepath.Join(h.dataDir, "bot-token"))
	if err != nil {
		return "", "", fmt.Errorf("read the local DSH bot token: %w", err)
	}
	token = strings.TrimSpace(string(b))
	if token == "" || strings.ContainsAny(token, "\r\n") {
		return "", "", fmt.Errorf("invalid local DSH bot token")
	}
	return "http://" + h.target, token, nil
}

// Regenerates src/client/scheme.css from the DSH host token sheet
// (packages/client/ui-theme/src/styles/design-platform.css, same release as
// package.json's @deepseek-ai/* deps). The host picks its palette with a global
// body[data-ds-dark-theme]; this plugin keeps its own light/dark choice, so the
// same declarations are re-scoped to [data-dc-scheme] on the plugin's own roots.
// Usage: node scripts/gen-scheme-css.mjs <design-platform.css>
import { readFileSync, writeFileSync } from 'node:fs'

const src = process.argv[2]
if (!src) { console.error('usage: gen-scheme-css.mjs <design-platform.css>'); process.exit(2) }
const text = readFileSync(src, 'utf8').replace(/\/\*[\s\S]*?\*\//g, '')
const map = new Map([
  ['body', "[data-dc-scheme='light']"],
  ['body[data-ds-dark-theme]', "[data-dc-scheme='dark']"],
  ["html[data-platform='darwin'] body", "html[data-platform='darwin'] [data-dc-scheme='light']"],
  ["html[data-platform='darwin'] body[data-ds-dark-theme]", "html[data-platform='darwin'] [data-dc-scheme='dark']"],
])
const out = ['/* Generated by scripts/gen-scheme-css.mjs from the DSH host design-platform.css — do not edit by hand. */']
for (const [, sel, body] of text.matchAll(/([^{}]+)\{([^{}]*)\}/g)) {
  const key = sel.trim().replace(/\s+/g, ' ')
  const target = map.get(key)
  if (!target) throw new Error(`unmapped selector: ${key}`)
  const decls = body.split(';').map(d => d.trim()).filter(d => d.startsWith('--'))
  if (!decls.length) continue
  out.push(`${target} {\n${decls.map(d => `  ${d};`).join('\n')}\n}`)
}
out.push("[data-dc-scheme='light'] { color-scheme: light; }", "[data-dc-scheme='dark'] { color-scheme: dark; }")
writeFileSync(new URL('../src/client/scheme.css', import.meta.url), out.join('\n\n') + '\n')

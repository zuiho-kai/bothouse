// The dsh sources that ship twice: once as the editable tree under dsh/, and once
// inside bridge/core/dsh_bundle so the one-click installer can unpack them without
// the repo. Keeping both in step was manual work (#133, #138, #141 all re-typed the
// copy by hand), so the pairing lives here in one place for check and sync.
import { existsSync, readdirSync, statSync } from 'node:fs'
import { join, relative, sep } from 'node:path'

export const BUNDLE = 'bridge/core/dsh_bundle'

// Copied verbatim, byte for byte.
export const COPY_PAIRS = [
  { from: 'dsh/collab', to: `${BUNDLE}/collab` },
  // Single files, not trees: compared and copied as one path each.
  { from: 'dsh/install.sh', to: `${BUNDLE}/install.sh`, file: true },
  {
    from: 'dsh/packages/client-ui-discord/package.json',
    to: `${BUNDLE}/packages/client-ui-discord/package.json`,
    file: true,
  },
]

// Never mirrored: the install lockfile is generated by the installer, the npm
// metadata is local, and the collab tests run from dsh/ only.
export const COPY_SKIP = new Set(['.npmrc', 'package-lock.json', 'test'])

// Built from dsh/packages/client-ui-discord/src by the package build, so it cannot
// be compared with a source file; it is checked for staleness instead.
export const BUILT_PAIRS = [
  {
    src: 'dsh/packages/client-ui-discord/src',
    from: 'dsh/packages/client-ui-discord/lib',
    to: `${BUNDLE}/packages/client-ui-discord/lib`,
  },
]

// What wrap-client.mjs writes at the head of the bundled client; a mirror without it
// is a raw build the installer cannot load.
export const BUNDLE_WRAPPER_MARKER = 'window.__ModuleLoader__.load'

export function walk(dir, base = dir) {
  if (!existsSync(dir)) return []
  const out = []
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    if (COPY_SKIP.has(entry.name)) continue
    const full = join(dir, entry.name)
    if (entry.isDirectory()) out.push(...walk(full, base))
    else out.push(relative(base, full).split(sep).join('/'))
  }
  return out.sort()
}

export function isBuiltFile(path) {
  return statSync(path).isFile()
}

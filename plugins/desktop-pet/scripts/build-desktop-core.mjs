#!/usr/bin/env node
/**
 * 把共享层（src/shared）构建成桌面 Helper 的经典 script：runtime/electron-helper/shared-core.js，挂到全局 window.PetShared。
 * 必须是经典 script 而非 ESM：桌面 Helper 从 file:// 载入页面，Chromium 对 file:// 的 ES module 有 CORS 限制。
 * shared-core.js 先于 renderer.js 加载，renderer 直接读全局，不再另建模块系统。
 * 只产这一份构建产物，不做类型检查、不写声明；由发布链的 npm run build:desktop-core 调用。
 * @module dsh-pet/scripts/build-desktop-core
 */
import { rolldown } from 'rolldown';
import { readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(fileURLToPath(new URL('..', import.meta.url)));
const OUT = join(ROOT, 'runtime', 'electron-helper', 'shared-core.js');

try {
  const bundle = await rolldown({
    input: join(ROOT, 'src', 'shared', 'index.ts'),
    platform: 'browser',
  });
  await bundle.write({
    format: 'iife',
    name: 'PetShared',
    file: OUT,
  });
  // 产物提交进仓库且由 Helper 从 file:// 加载：文件头必须声明生成来源，避免被手改后又被构建无声覆盖。
  const banner = [
    '/**',
    ' * @generated by `npm run build:desktop-core`（scripts/build-desktop-core.mjs），请勿手改。',
    ' * 源文件：src/shared/index.ts。',
    ' */',
  ].join('\n');
  const code = readFileSync(OUT, 'utf8');
  if (!code.startsWith('/**')) writeFileSync(OUT, banner + '\n' + code);
  console.log('[build-desktop-core] ✓ runtime/electron-helper/shared-core.js (window.PetShared)');
} catch (error) {
  console.error('[build-desktop-core] build failed:', error);
  process.exit(1);
}

#!/usr/bin/env python3
"""Generate cn_dial/dial_layout_v1.h from layout/dial-layout.v1.json.

The JSON is the only place the numbers live; the C++ header is generated so firmware without a
JSON parser can use them. `--check` exits 1 when the committed header is stale (CI runs it).
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "layout" / "dial-layout.v1.json"
OUT = ROOT / "components" / "cn_dial" / "include" / "cn_dial" / "dial_layout_v1.h"


def ident(item_id: str) -> str:
    parts = re.split(r"[._]", item_id)
    return "k" + "".join(p[:1].upper() + p[1:] for p in parts)


def num(v) -> str:
    s = repr(float(v))
    return s + "f"


def render(d: dict) -> str:
    if d.get("schema") != "cn_dial.layout" or d.get("version") != 1:
        raise SystemExit("unexpected schema/version")
    lines = [
        "// Generated by firmware/dial/tools/gen_layout.py from layout/dial-layout.v1.json -- do not edit.",
        "#pragma once",
        "",
        '#include "cn_dial/layout_types.h"',
        "",
        "namespace cn_dial::layout {",
        "",
        f"inline constexpr int kCanvas = {int(d['canvas'])};",
        "",
    ]
    seen = set()
    for it in d["items"]:
        name = ident(it["id"])
        if name in seen:
            raise SystemExit(f"duplicate id {it['id']}")
        seen.add(name)
        kinds = [k for k in ("design", "fixed_px", "frac", "deg") if k in it]
        if len(kinds) != 1 or not it.get("src"):
            raise SystemExit(f"{it['id']}: need exactly one of design/fixed_px/frac/deg and a src")
        kind = kinds[0]
        if kind == "design":
            decl = f"inline constexpr Px {name}{{{num(it['design'])}, {int(it.get('min_px', 1))}}};"
        elif kind == "fixed_px":
            decl = f"inline constexpr Px {name}{{0.0f, {int(it['fixed_px'])}}};  // fixed"
        elif kind == "frac":
            decl = f"inline constexpr Frac {name}{{{num(it['frac'])}}};"
        else:
            decl = f"inline constexpr float {name} = {num(it['deg'])};  // degrees"
        lines.append(f"// {it['id']}: {it['src']}")
        lines.append(decl)
    lines.append("")
    for f in d["fonts"]:
        name = ident(f["id"])
        if name in seen or not f.get("src"):
            raise SystemExit(f"bad font {f['id']}")
        seen.add(name)
        lines.append(f"// {f['id']}: {f['src']}")
        lines.append(f"inline constexpr Font {name}{{{int(f['design_px'])}, {int(f['lines'])}}};")
    lines += ["", "}  // namespace cn_dial::layout", ""]
    return "\n".join(lines)


def main() -> int:
    text = render(json.loads(SRC.read_text(encoding="utf-8")))
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print(f"{OUT} is stale: run python3 firmware/dial/tools/gen_layout.py", file=sys.stderr)
            return 1
        print("layout header up to date")
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
